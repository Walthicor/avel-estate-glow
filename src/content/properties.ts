/**
 * Localised alt text for every property photograph.
 * Derived once at module load so each record always carries alt_en / alt_es.
 */
const withAlt = (p: PropertyRecord): PropertyRecord => ({
  ...p,
  alt_en: `${p.titleEn} — ${p.typeEn.toLowerCase()} in ${p.zone}, ${p.cityLabel}, Colombia`,
  alt_es: `${p.titleEn} — ${p.typeEs.toLowerCase()} en ${p.zone}, ${p.cityLabel}, Colombia`,
});

export const PROPERTIES = RAW.map(withAlt);

export const propertyAlt = (p: PropertyRecord, locale: Locale) =>
  (locale === "es" ? p.alt_es : p.alt_en) ??
  `${p.titleEn}, ${p.zone}, ${p.cityLabel}`;

export const imageFor = (p: PropertyRecord) => propertyCover(p.slug);


export const CITY_OPTIONS = [
  { value: "medellin", label: "Medellín" },
  { value: "cartagena", label: "Cartagena" },
  { value: "bogota", label: "Bogotá" },
  { value: "santa-marta", label: "Santa Marta" },
];

export const TYPE_OPTIONS = [
  { value: "apartment", en: "Apartment", es: "Apartamento" },
  { value: "penthouse", en: "Penthouse", es: "Penthouse" },
  { value: "house", en: "House", es: "Casa" },
  { value: "aparthotel", en: "Aparthotel", es: "Aparthotel" },
];

export const STAGE_OPTIONS = [
  { value: "pre-construction", en: "Pre-construction", es: "Preventa" },
  { value: "ready", en: "Ready", es: "Entrega inmediata" },
];

export const typeLabel = (p: PropertyRecord, locale: Locale) =>
  locale === "es" ? p.typeEs : p.typeEn;

export const stageLabel = (stage: PropertyStage, locale: Locale) =>
  STAGE_OPTIONS.find((s) => s.value === stage)?.[locale] ?? stage;

export const deliveryLabel = (p: PropertyRecord, locale: Locale) =>
  p.delivery ? (locale === "es" ? `Entrega ${p.delivery}` : `Delivery ${p.delivery}`) : "";

export const bedroomsLabel = (p: PropertyRecord, locale: Locale) => {
  const range = p.bedroomsMin === p.bedroomsMax ? `${p.bedroomsMin}` : `${p.bedroomsMin}–${p.bedroomsMax}`;
  return locale === "es" ? `${range} hab.` : `${range} bed`;
};

export const areaLabel = (p: PropertyRecord) => `${p.areaMin} – ${p.areaMax} m²`;
